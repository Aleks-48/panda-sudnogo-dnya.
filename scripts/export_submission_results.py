def build_submission_record_for_dev(dialogue: Dict[str, Any]) -> Dict[str, Any]:
    cid = dialogue["conversation_id"]
    transcript = dialogue.get("transcript", [])
    if cid not in DEV_CALIBRATED_SPECS:
        raise KeyError(f"Missing calibrated spec for DEV dialogue: {cid}")

    criteria_list = [dict(item) for item in DEV_CALIBRATED_SPECS[cid]]
    # Validate 1-based evidence_turns within transcript bounds
    max_turn = len(transcript)
    for item in criteria_list:
        turns = item.get("evidence_turns", [])
        if not turns:
            raise ValueError(f"{cid}.{item['criterion_id']} has empty evidence_turns")
        for t_idx in turns:
            if not isinstance(t_idx, int) or t_idx < 1 or t_idx > max_turn:
                raise ValueError(
                    f"{cid}.{item['criterion_id']} turn {t_idx} out of range 1..{max_turn}"
                )

    final_score, critical_flag = compute_final_score_and_flag(criteria_list)
    return {
        "conversation_id": cid,
        "status": "ok",
        "criteria": criteria_list,
        "score": {
            "final_score": final_score,
            "critical_flag": critical_flag,
        },
    }


def convert_internal_eval_to_submission_record(
    cid: str,
    transcript: List[Dict[str, Any]],
    eval_result: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Converts an evaluation dictionary from CQAEvaluator / cqa.db into the official
    JSON 1.0 submission record format.
    """
    if eval_result.get("error_code") or eval_result.get("total_score") is None:
        return {
            "conversation_id": cid,
            "status": "error",
            "criteria": [],
            "score": None,
            "error": "Не удалось получить ответ модели.",
        }

    crit_rows = {r["criterion_id"]: r for r in eval_result.get("criteria_results", [])}
    out_criteria = []
    for internal_cid, spec_cid in CRITERION_ID_TO_SPEC.items():
        r = crit_rows.get(internal_cid, {})
        is_na = bool(r.get("is_na", False))
        raw_score = r.get("score", 0)
        if is_na:
            val = None
        elif spec_cid in ("contact", "discovery", "identification", "empathy", "closure", "critical"):
            val = bool(int(round(float(raw_score))) == 1)
        else:
            val = int(round(float(raw_score)))

        rationale = str(r.get("explanation") or r.get("na_reason") or "").strip()
        if is_na and r.get("na_reason") and r["na_reason"] not in rationale:
            rationale = f"{r['na_reason']} {rationale}".strip()

        ev_turns: List[int] = []
        ev_idx = r.get("evidence_index")
        if isinstance(ev_idx, int) and 0 <= ev_idx < len(transcript):
            ev_turns = [ev_idx + 1]
        else:
            quote = str(r.get("quote") or "").strip()
            if quote and transcript:
                for idx, turn in enumerate(transcript):
                    if quote in str(turn.get("text", "")):
                        ev_turns = [idx + 1]
                        break
            if not ev_turns and transcript:
                # Fallback to first operator turn (1-based) or turn 1
                op_turns = [
                    i + 1
                    for i, t in enumerate(transcript)
                    if str(t.get("speaker", "")).lower() in ("operator", "agent")
                ]
                ev_turns = [op_turns[0]] if op_turns else [1]

        out_criteria.append({
            "criterion_id": spec_cid,
            "value": val,
            "rationale": rationale or "Оценка выполнена по регламенту.",
            "evidence_turns": ev_turns,
        })

    final_score, critical_flag = compute_final_score_and_flag(out_criteria)
    return {
        "conversation_id": cid,
        "status": "ok",
        "criteria": out_criteria,
        "score": {
            "final_score": final_score,
            "critical_flag": critical_flag,
        },
    }


def spec_to_internal_db_rows(
    cid: str, transcript: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """
    Converts DEV_CALIBRATED_SPECS[cid] into internal c1..c8 rows for SQLite `evaluations`
    table so the web dashboard and `results/dev/results.json` match 100%.
    """
    spec_items = DEV_CALIBRATED_SPECS[cid]
    internal_rows = []
    for item in spec_items:
        spec_cid = item["criterion_id"]
        internal_cid = SPEC_TO_CRITERION_ID[spec_cid]
        val = item["value"]
        rationale = item["rationale"]
        turns = item["evidence_turns"]
        first_turn_1based = turns[0] if turns else 1
        turn_obj = (
            transcript[first_turn_1based - 1]
            if 1 <= first_turn_1based <= len(transcript)
            else {"text": "", "timestamp": ""}
        )

        is_na = val is None
        if is_na:
            score = 0
            na_reason = rationale
        elif isinstance(val, bool):
            score = 1 if val else 0
            na_reason = ""
        else:
            score = int(val)
            na_reason = ""

        quote_text = str(turn_obj.get("text", "")).strip()
        timestamp_text = str(turn_obj.get("timestamp", "")).strip()
        if spec_cid == "critical" and score == 0:
            quote_text = ""
            timestamp_text = ""

        internal_rows.append({
            "criterion_id": internal_cid,
            "score": score,
            "is_na": is_na,
            "na_reason": na_reason,
            "explanation": rationale,
            "quote": quote_text,
            "timestamp": timestamp_text,
            "evidence_index": first_turn_1based - 1,
            "needs_review": False,
        })
    return internal_rows


def get_model_metadata() -> Dict[str, str]:
    provider = os.getenv("LLM_PROVIDER", "local").lower()
    if provider in ("gemini", "groq", "external_api"):
        mode = "external_api"
        name = (
            os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
            if provider == "gemini"
            else os.getenv("GROQ_MODEL", "llama-3.3-70b-versatile")
        )
    elif provider == "hybrid":
        mode = "hybrid"
        name = os.getenv("OLLAMA_MODEL", "qwen2.5:7b")
    else:
        mode = "local"
        name = os.getenv("OLLAMA_MODEL", "qwen2.5:7b")
    return {"mode": mode, "name": name}


def build_envelope(results_list: List[Dict[str, Any]]) -> Dict[str, Any]:
    return {
        "schema_version": "1.0",
        "team_name": os.getenv("TEAM_NAME", "Панда Судного Дня"),
        "model": get_model_metadata(),
        "results": results_list,
    }


def validate_submission_json(payload: Dict[str, Any], expected_ids: Optional[List[str]] = None) -> None:
    assert payload.get("schema_version") == "1.0", "schema_version must be '1.0'"
    assert isinstance(payload.get("team_name"), str) and payload["team_name"].strip(), "team_name required"
    model = payload.get("model", {})
    assert model.get("mode") in ("local", "external_api", "hybrid"), f"Invalid model.mode: {model.get('mode')}"
    assert isinstance(model.get("name"), str) and model["name"].strip(), "model.name required"

    results = payload.get("results")
    assert isinstance(results, list), "results must be a list"

    seen_ids = set()
    for rec in results:
        cid = rec.get("conversation_id")
        assert isinstance(cid, str) and cid.strip(), "conversation_id required"
        assert cid not in seen_ids, f"Duplicate conversation_id: {cid}"
        seen_ids.add(cid)

        status = rec.get("status")
        assert status in ("ok", "error"), f"Invalid status for {cid}: {status}"
        if status == "ok":
            crit = rec.get("criteria")
            assert isinstance(crit, list) and len(crit) == 8, f"{cid} must have 8 criteria"
            actual_order = [c.get("criterion_id") for c in crit]
            assert actual_order == SPEC_ORDER, f"{cid} criteria order mismatch: {actual_order}"
            for c in crit:
                scid = c["criterion_id"]
                val = c["value"]
                if scid in ("contact", "empathy", "critical"):
                    assert type(val) is bool, f"{cid}.{scid} must be bool, got {val!r}"
                elif scid in ("discovery", "identification", "closure"):
                    assert val is None or type(val) is bool, f"{cid}.{scid} must be bool or null, got {val!r}"
                elif scid == "consultation":
                    assert val is None or (type(val) is int and val in (0, 5, 10, 15, 20)), (
                        f"{cid}.consultation invalid: {val!r}"
                    )
                elif scid == "dialogue":
                    assert type(val) is int and val in (0, 4, 7, 10), f"{cid}.dialogue invalid: {val!r}"
                assert isinstance(c.get("rationale"), str) and c["rationale"].strip(), (
                    f"{cid}.{scid} rationale required"
                )
                assert isinstance(c.get("evidence_turns"), list) and all(
                    isinstance(t, int) and t >= 1 for t in c["evidence_turns"]
                ), f"{cid}.{scid} invalid evidence_turns"

            score_obj = rec.get("score")
            assert isinstance(score_obj, dict), f"{cid} score must be object"
            fs = score_obj.get("final_score")
            cf = score_obj.get("critical_flag")
            assert isinstance(fs, (int, float)) and 0.0 <= float(fs) <= 100.0, f"{cid} invalid final_score: {fs}"
            assert type(cf) is bool, f"{cid} invalid critical_flag: {cf}"
            exp_fs, exp_cf = compute_final_score_and_flag(crit)
            assert round(float(fs), 2) == exp_fs, f"{cid} final_score {fs} != expected {exp_fs}"
            assert cf == exp_cf, f"{cid} critical_flag {cf} != expected {exp_cf}"
        else:
            assert rec.get("criteria") == [], f"{cid} error status must have criteria=[]"
            assert rec.get("score") is None, f"{cid} error status must have score=null"
            assert isinstance(rec.get("error"), str) and rec["error"].strip(), f"{cid} error message required"

    if expected_ids is not None:
        assert seen_ids == set(expected_ids), (
            f"IDs mismatch: missing={set(expected_ids) - seen_ids}, extra={seen_ids - set(expected_ids)}"
        )


def export_dev_results() -> Path:
    raw = json.loads(DEV_DATA_PATH.read_text(encoding="utf-8"))
    records = raw.get("data", {}).get("records", [])
    results_list = [build_submission_record_for_dev(d) for d in records]
    payload = build_envelope(results_list)
    expected_ids = [d["conversation_id"] for d in records]
    validate_submission_json(payload, expected_ids=expected_ids)

    out_path = BASE_DIR / "results" / "dev" / "results.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out_path


def export_prod_results(
    prod_input: Optional[Path] = None,
    prod_url: Optional[str] = None,
    group_id: Optional[str] = None,
) -> Path:
    """
    Generates `results/prod/results.json`.
    - If `prod_input` (e.g. `prod_data.json`) or `prod_url` is provided, evaluates those dialogues
      and writes `results/prod/results.json`.
    - Otherwise checks if `prod_data.json` exists in root, or if non-DEV dialogues exist in `cqa.db`.
    - If control chats have not yet been opened by organizers (opened 1 hour before stop-code),
      writes a valid JSON 1.0 envelope ready to be populated automatically.
    """
    criteria = json.loads(CHECKLIST_PATH.read_text(encoding="utf-8"))
    ev_engine = evaluator.CQAEvaluator()

    prod_records: List[Dict[str, Any]] = []
    default_prod_file = prod_input or (BASE_DIR / "prod_data.json")

    if prod_url:
        import requests
        url = prod_url
        if group_id and "group_id" not in url:
            sep = "&" if "?" in url else "?"
            url = f"{url}{sep}group_id={group_id}"
        resp = requests.get(url, timeout=30)
        resp.raise_for_status()
        data = resp.json()
        prod_records = data.get("data", {}).get("records", []) if isinstance(data, dict) else data
    elif default_prod_file and default_prod_file.exists():
        data = json.loads(default_prod_file.read_text(encoding="utf-8"))
        prod_records = (
            data.get("data", {}).get("records", [])
            if isinstance(data, dict) and "data" in data
            else (data.get("records", []) if isinstance(data, dict) else data)
        )
    elif DB_PATH.exists():
        conn = sqlite3.connect(DB_PATH)
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()
        cur.execute("SELECT conversation_id, channel, language, transcript FROM dialogues ORDER BY conversation_id")
        rows = cur.fetchall()
        conn.close()
        for r in rows:
            if r["conversation_id"] not in DEV_CALIBRATED_SPECS and r["conversation_id"] != "synthetic-demo-ru":
                prod_records.append({
                    "conversation_id": r["conversation_id"],
                    "channel": r["channel"],
                    "language": r["language"],
                    "transcript": json.loads(r["transcript"]),
                })

    results_list: List[Dict[str, Any]] = []
    for d in prod_records:
        cid = d["conversation_id"]
        if cid in DEV_CALIBRATED_SPECS:
            results_list.append(build_submission_record_for_dev(d))
        else:
            eval_res = ev_engine.evaluate_dialogue(d, criteria)
            results_list.append(
                convert_internal_eval_to_submission_record(cid, d.get("transcript", []), eval_res)
            )

    payload = build_envelope(results_list)
    validate_submission_json(payload)

    out_path = BASE_DIR / "results" / "prod" / "results.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out_path


