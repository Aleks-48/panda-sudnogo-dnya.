def _c(
    criterion_id: str,
    value: Any,
    rationale: str,
    evidence_turns: List[int],
) -> Dict[str, Any]:
    return {
        "criterion_id": criterion_id,
        "value": value,
        "rationale": rationale,
        "evidence_turns": list(evidence_turns),
    }


def compute_final_score_and_flag(criteria_items: List[Dict[str, Any]]) -> Tuple[float, bool]:
    """
    Computes final_score (0..100 rounded to 2 decimal places) with proportional
    weight redistribution for N/A (value is None) criteria, and critical_flag.
    """
    by_id = {item["criterion_id"]: item for item in criteria_items}
    applicable_weight = 0.0
    for cid in SPEC_ORDER:
        if cid == "critical":
            continue
        item = by_id[cid]
        if item["value"] is not None:
            applicable_weight += SPEC_WEIGHTS[cid]

    if applicable_weight <= 0:
        final_score = 0.0
    else:
        accum = 0.0
        for cid in SPEC_ORDER:
            if cid == "critical":
                continue
            val = by_id[cid]["value"]
            if val is None:
                continue
            weight = SPEC_WEIGHTS[cid]
            eff_weight = (weight / applicable_weight) * 100.0
            if isinstance(val, bool):
                ratio = 1.0 if val else 0.0
            else:
                ratio = float(val) / SPEC_MAX_POINTS[cid]
            accum += ratio * eff_weight
        final_score = round(accum, 2)

    critical_flag = bool(by_id["critical"]["value"])
    return final_score, critical_flag


